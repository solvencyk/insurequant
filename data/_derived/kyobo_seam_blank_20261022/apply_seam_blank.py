def git_json(rev, rel):
    p = subprocess.run(["git", "-C", str(ROOT), "show", f"{rev}:{rel}"], capture_output=True)
    if p.returncode != 0:
        raise SystemExit(f"git show {rev}:{rel} failed: {p.stderr.decode('utf-8', 'replace')[:200]}")
    return json.loads(p.stdout.decode("utf-8"))


def rkey(r):
    return (r["원보험사코드"], r["항목번호"], r["공시분기"])


def blank_set():
    """the cells 3e53aef8 filled: 값_당분기 null at 3e53aef8~1 -> not null at 3e53aef8 (KR0073 2023.3Q)."""
    b = {rkey(r): r for r in git_json(BASE_REV, F["PL"]) if r["원보험사코드"] == CODE and r["공시분기"] == QTR}
    a = {rkey(r): r for r in git_json(REFRESH_REV, F["PL"]) if r["원보험사코드"] == CODE and r["공시분기"] == QTR}
    items = sorted(k[1] for k in a if b[k].get("값_당분기") is None and a[k].get("값_당분기") is not None)
    keep = sorted(k[1] for k in a if b[k].get("값_당분기") is not None)
    if items != EXPECT_ITEMS or keep != KEEP_ITEMS:
        raise SystemExit(f"ABORT: git-derived sets moved: blank {items} (expected {EXPECT_ITEMS}); keep {keep} (expected {KEEP_ITEMS})")
    return items, {k[1]: a[k].get("값_당분기") for k in a}, {k[1]: b[k].get("값_당분기") for k in b}


def text_edit(raw, edits, label):
    out = raw
    for old, new in edits:
        if out.count(old) != 1:
            raise SystemExit(f"ABORT: anchor not found exactly once in {label}: {old[:60]!r} (count {out.count(old)})")
        out = out.replace(old, new)
    return out


def patched_module(src_text):
    """executes the patched builder source in memory (no repo write); __file__ stays the real path so ROOT-relative constants resolve."""
    path = ROOT / BRM_REL
    mod = types.ModuleType("brm_patched")
    mod.__file__ = str(path)
    exec(compile(src_text, str(path), "exec"), mod.__dict__)
    return mod


def run_build_pl(mod, gold_obj, tag):
    tmpdir = EV / "tmp_apply"
    tmpdir.mkdir(exist_ok=True)
    gp, mp = tmpdir / f"gold_{tag}.json", tmpdir / f"master_{tag}.json"
    gp.write_text(json.dumps(gold_obj, ensure_ascii=False, indent=2), encoding="utf-8", newline="\n")
    shutil.copyfile(ROOT / F["PL"], mp)
    mod.PL_OVR, mod.PL_OUT = gp, mp
    mod.build_pl()
    rows = json.loads(mp.read_text(encoding="utf-8"))
    for p in (gp, mp):
        try:
            p.unlink()
        except OSError:
            pass
    return rows


def splice(live_rows, sim_rows):
    sim_by = {rkey(r): r for r in sim_rows}
    if len(sim_rows) != len(live_rows):
        raise SystemExit(f"ABORT: builder row count {len(sim_rows)} != live {len(live_rows)}")
    new_rows, val_changed, dangi_changed, other_drift = [], [], [], []
    for r in live_rows:
        s = sim_by.get(rkey(r))
        if s is None:
            raise SystemExit(f"ABORT: {rkey(r)} missing from the builder simulation")
        if r["원보험사코드"] == CODE:
            nr = dict(r)
            nr["값"], nr["값_당분기"] = s["값"], s["값_당분기"]
            new_rows.append(nr)
            if nr["값"] != r["값"]:
                val_changed.append(rkey(r))
            if nr["값_당분기"] != r.get("값_당분기"):
                dangi_changed.append(rkey(r))
        else:
            if (r["값"], r.get("값_당분기")) != (s["값"], s.get("값_당분기")):
                other_drift.append(rkey(r))
            new_rows.append(r)
    return new_rows, val_changed, dangi_changed, other_drift


def plan():
    live = {k: ak.JsonFile(rel) for k, rel in F.items()}
    brm_raw = (ROOT / BRM_REL).read_text(encoding="utf-8")
    test_raw = (ROOT / TEST_REL).read_text(encoding="utf-8")
    for label, t in ((BRM_REL, brm_raw), (TEST_REL, test_raw)):
        if "\r" in t:
            raise SystemExit(f"ABORT: {label} has CR characters")
    items, head_dangi, base_dangi = blank_set()

    # ---- guards: the live master is at the 3e53aef8 state for those cells
    cur = {rkey(r): r for r in live["PL"].obj if r["원보험사코드"] == CODE and r["공시분기"] == QTR}
    bad = [(i, cur[(CODE, i, QTR)].get("값_당분기"), head_dangi[i]) for i in items
           if cur[(CODE, i, QTR)].get("값_당분기") not in (None, head_dangi[i]) and abs((cur[(CODE, i, QTR)].get("값_당분기") or 0) - head_dangi[i]) > 5e-4]
    if bad:
        raise SystemExit(f"ABORT: live 값_당분기 of the target cells moved since 3e53aef8: {bad[:5]}")

    # ---- gold: + null_dangi (union with an existing list, so a later extension is idempotent)
    gold = copy.deepcopy(live["GOLD"].obj)
    old_cells = [tuple(c) for c in (gold.get("null_dangi") or {}).get("cells", [])]
    want = sorted({(CODE, QTR, i) for i in items} | set(old_cells), key=lambda c: (c[0], c[1], c[2]))
    doc = gold.get("_doc", "")
    if DOC_SENTENCE.strip() not in doc:
        gold["_doc"] = doc + DOC_SENTENCE
    gold["null_dangi"] = {"_doc": NULL_DANGI_DOC, "cells": [list(c) for c in want]}

    # ---- builder text + real patched build_pl()
    new_brm = text_edit(brm_raw, BRM_EDITS, BRM_REL) if "_pl_null_dangi_keys" not in brm_raw else brm_raw
    mod = patched_module(new_brm)
    sim = run_build_pl(mod, gold, "plan")
    new_rows, val_changed, dangi_changed, other_drift = splice(live["PL"].obj, sim)

    new_test = test_raw if "test_pl_null_dangi_blanks_only_the_listed_single_quarter" in test_raw else test_raw.rstrip("\n") + "\n" + NEW_TESTS

    errs = []
    if val_changed:
        errs.append(f"cumulative 값 changed: {val_changed[:5]}")
    target = {(CODE, i, QTR) for i in items}
    already = {k for k in target if cur[k].get("값_당분기") is None}
    expect_changed = target - already
    if set(dangi_changed) != expect_changed:
        errs.append(f"값_당분기 changed set != expected: extra {sorted(set(dangi_changed) - expect_changed)[:5]} missing {sorted(expect_changed - set(dangi_changed))[:5]}")
    nb = {rkey(r): r for r in new_rows}
    for k in target:
        if nb[k].get("값_당분기") is not None:
            errs.append(f"target not blank: {k}")
    # untouched: keep items, 2023.4Q, 2024.3Q and every other KR0073 cell identical to the live master
    for r_old, r_new in zip(live["PL"].obj, new_rows):
        if r_old["원보험사코드"] == CODE and rkey(r_old) not in target:
            if (r_old["값"], r_old.get("값_당분기")) != (r_new["값"], r_new.get("값_당분기")):
                errs.append(f"unexpected change {rkey(r_old)}")
    snap = EV / "pl_drift_before_seam.json"
    if not snap.exists():
        errs.append("pl_drift_before_seam.json missing: run --snapshot-drift before the apply")
    else:
        before = {tuple(x) for x in json.loads(snap.read_text(encoding="utf-8"))["non_kr0073_drift"]}
        if before != set(other_drift):
            errs.append(f"non-KR0073 drift changed vs snapshot: {len(before)} -> {len(other_drift)}")
    return dict(live=live, items=items, gold=gold, new_rows=new_rows, new_brm=new_brm, brm_raw=brm_raw, new_test=new_test, test_raw=test_raw,
                dangi_changed=dangi_changed, already=already, other_drift=other_drift, errs=errs, head_dangi=head_dangi, base_dangi=base_dangi)


