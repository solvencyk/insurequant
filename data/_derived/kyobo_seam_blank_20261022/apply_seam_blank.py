    snap = {tuple(x) for x in json.loads((EV / "pl_drift_before_seam.json").read_text(encoding="utf-8"))["non_kr0073_drift"]}
    kr = sum(1 for r in live_rows if r["원보험사코드"] == CODE)
    ok1 = not vc and not dc
    ok2 = set(other) == snap
    print(f"verify: KR0073 rows {kr}; fresh real build_pl() (live builder + live gold) differs from live in {len(set(vc) | set(dc))} KR0073 cells -> {'OK' if ok1 else 'FAIL'}")
    print(f"verify: non-KR0073 drift now {len(other)} vs snapshot {len(snap)} -> {'OK (identical set)' if ok2 else 'FAIL'}")
    items, head_dangi, _b = blank_set()
    head_rows = {rkey(r): r for r in git_json("HEAD", F["PL"]) if r["원보험사코드"] == CODE}
    now = {rkey(r): r for r in live_rows if r["원보험사코드"] == CODE}
    diff_cells = [k for k in now if (now[k]["값"], now[k].get("값_당분기")) != (head_rows[k]["값"], head_rows[k].get("값_당분기"))]
    val_diff = [k for k in now if now[k]["값"] != head_rows[k]["값"]]
    target = {(CODE, i, QTR) for i in items}
    ok3 = set(diff_cells) <= target and not val_diff and all(now[k].get("값_당분기") is None for k in target)
    print(f"verify: vs git HEAD the live KR0073 PL differs in {len(diff_cells)} cells (all inside the 28 targets: {set(diff_cells) <= target}); cumulative 값 diffs {len(val_diff)}; "
          f"all 28 targets blank: {all(now[k].get('값_당분기') is None for k in target)} -> {'OK' if ok3 else 'FAIL'}")
    return ok1 and ok2 and ok3


