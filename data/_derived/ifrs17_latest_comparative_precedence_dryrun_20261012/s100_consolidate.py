def pick_verdict(rows):
    """FY/quarter bundle verdict: no-change / no-column rows are ignored when anything else exists; a bundle that is partly gold-blocked, tool-blocked or kept is NOT adopted."""
    if not rows:
        return None
    vs = [r["verdict"] for r in rows]
    S = set(vs)
    core = S - {V_SAME, V_NOEX}
    if not core:
        return V_SAME if V_SAME in S else V_NOEX
    if core <= set(ADOPT):
        return V_EXC if V_EXC in core else V_DAG
    for v in (V_GOLD, V_UNV, V_COND, V_BOTH, V_KEEP, V_PRIOR):
        if v in core:
            return v + ("" if len(core) == 1 else " (번들: " + ", ".join(f"{k}×{n}" for k, n in Counter(x for x in vs if x in core).most_common()) + ")")
    return " / ".join(f"{k}×{n}" for k, n in Counter(vs).most_common())


