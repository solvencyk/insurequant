def quarters_of(s):
    out = []
    for part in re.split(r"[·,]", s or ""):
        part = part.strip()
        m = re.fullmatch(r"FY(\d{4})", part)
        if m:
            out += [f"{m.group(1)}.{k}Q" for k in (1, 2, 3, 4)]
        elif re.fullmatch(r"\d{4}\.\dQ", part):
            out.append(part)
        else:
            m2 = re.fullmatch(r"(\d{4}\.\dQ)~(\d{4}\.\dQ)", part)
            if m2:
                out += [m2.group(1), m2.group(2)]
    return out


