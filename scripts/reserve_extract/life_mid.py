# ---------------------------------------------------------------- KR0079 미래에셋생명
_MIRAE_T_CONCEPTS = ("대손준비금", "해약환급금준비금", "보증준비금")


def _mirae_transposed(ctx: FilingContext, item: int) -> float | None:
    """P2 전치형 `준비금잔액` 행에서 개념 컬럼 값을 꺼낸다.

    같은 필링 앞쪽에 헤더가 비슷한 **이익잉여금 구성 전치표**(행 라벨 `이익잉여금`)가 먼저
    오는데 그건 기적립액이라 쓰면 안 된다 -- 행 라벨을 `준비금잔액`으로 못박아 구분한다.
    2026.2Q 실측(라인 25560, 단위 원): 기적립액 1,219,968,190,692 + 예정액 168,900,958,077
    = 잔액 1,388,869,148,769(= 1,388,869백만원)로 정확히 닫힌다.
    """
    concept = _STEMS[item][0]
    for t in ctx.tables:
        hdr = [norm(c) for c in (t.header[-1] if t.header else [])]
        if concept not in hdr or sum(1 for c in hdr if c in _MIRAE_T_CONCEPTS) < 2:
            continue
        idx = hdr.index(concept)
        for r in t.rows:
            if not r or not r[0] or strip_label(r[0]) != "준비금잔액" or idx >= len(r):
                continue
            v = num(r[idx])
            if v is not None:
                return abs(scale_guard(v, ctx.find_unit(t.line_no), t.line_no))
    return None


def extract_mirae(ctx: FilingContext) -> dict[int, float]:
    """미래에셋생명 -- 연차는 P1(라벨형 `<개념>잔액`), 분기는 P2(전치형).

    2023 연차 실측: 해약환급금준비금 기적립액 '-' / 전입예정 900,203 / 잔액 900,203,
    보증준비금 '-' / 168,174 / 168,174, 대손준비금 40,812 / (25,939) / 14,873.
    잔액 행이 이미 기적립+예정이므로 예정액을 또 더하면 안 된다(P1 규칙).

    연도 경계 검산이 전 구간 닫힌다: 2024 연차 결과 992,343 = 2026.2Q 표의 전기말 기적립액
    992,343,160,905, 2025 연차 결과 1,219,968 = 2026.2Q 표의 당반기말 기적립액
    1,219,968,190,692.
    """
    out: dict[int, float] = {}
    for item in (5, 6, 7, 8):
        v = _p1(ctx, item)
        if v is None:
            v = _mirae_transposed(ctx, item)
        if v is not None:
            out[item] = v
    return out


