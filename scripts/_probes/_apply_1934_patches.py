def build_meta(rows, code):
    for r in rows:
        if r["원보험사코드"] == code:
            return {"원수사명": r["원수사명"], "티커": r["티커"], "생손보여부": r["생손보여부"]}
    return None


def apply_patches(rows: list[dict]) -> dict:
    """UPSERT all CELLS into rows (in place). Returns stats."""
    existing = {(r["원보험사코드"], r["항목번호"], r["공시분기"]): r for r in rows}
    n_insert = 0
    n_update = 0
    for code, cells in CELLS.items():
        meta = build_meta(rows, code)
        if meta is None:
            print(f"!! no meta found for {code}, skip")
            continue
        for item_no, label, value, value_after, reason in cells:
            key = (code, item_no, Q)
            if key in existing:
                row = existing[key]
                before = row.get("값")
                row["값"] = value
                if value_after is not None:
                    row["값_적용후"] = value_after
                n_update += 1
                if str(before) != str(value):
                    print(f"  UPDATE {code} item{item_no}: {before!r} -> {value!r}")
            else:
                new_row = {**meta, "원보험사코드": code, "항목번호": item_no,
                           "항목명": label, "공시분기": Q, "값": value}
                if value_after is not None:
                    new_row["값_적용후"] = value_after
                rows.append(new_row)
                existing[key] = new_row
                n_insert += 1
    return {"insert": n_insert, "update": n_update}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--scratch", type=str, default=None)
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    rows = json.loads(LIVE.read_text(encoding="utf-8"))
    before_n = len(rows)
    before_combos = {(r["원보험사코드"], r["항목번호"], r["공시분기"]) for r in rows}

    stats = apply_patches(rows)
    after_n = len(rows)
    after_combos = {(r["원보험사코드"], r["항목번호"], r["공시분기"]) for r in rows}

    print(f"\nrows before={before_n} after={after_n} (+{after_n - before_n})")
    print(f"insert={stats['insert']} update={stats['update']}")
    print(f"new combos added={len(after_combos - before_combos)} (should equal insert count)")
    print(f"combos removed={len(before_combos - after_combos)} (must be 0)")

    if args.dry_run:
        print("\n(dry-run; no write)")
        return

    out_path = Path(args.scratch) if args.scratch else LIVE
    out_path.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nwrote {len(rows)} rows to {out_path}")


if __name__ == "__main__":
    main()
