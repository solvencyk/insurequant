def s(x):
    """Format a numeric value the way _to_eok does: int-string if whole, else 2dp trimmed."""
    if x is None:
        return None
    f = float(x)
    if abs(f - round(f)) < 1e-9:
        return str(int(round(f)))
    return f"{f:.2f}".rstrip("0").rstrip(".")


